#!/usr/bin/env python3
"""Generate src/tables.rs and unit-test fixtures for the srtstripper Rust port.

The oracle is this Python runtime's own behavior; the generated tables freeze
it so the Rust port can match byte-for-byte without runtime Unicode tables.

Oracle definitions (all from the deprecated strip_srt.py):
  LETTER: re.compile(r"[^\\W\\d_]")  -> has_letter()
  DIGIT : re.compile(r"\\d")           -> timecode fields (Unicode decimal digits)
  SPACE : re.compile(r"\\s")           -> timecode \\s* and (verified equal)
                                          str.isspace() used by is_blank/strip()
  CP1252: bytes 0..255 decoded as cp1252; byte is undefined -> sentinel 0x110000

Outputs (all deterministic):
  src/tables.rs
  src/testdata/letter_sample.tsv
  src/testdata/timecode_lines.txt
  src/testdata/timecode_expected.txt
  src/testdata/splitlines_cases.rs
  src/testdata/trim_cases.rs
  src/testdata/blank_cases.rs
  src/testdata/decode_cases.rs
  src/testdata/stem_cases.rs
"""
import hashlib
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRATE = HERE.parent
SRC = CRATE / "src"
TESTDATA = SRC / "testdata"

LETTER = re.compile(r"[^\W\d_]")
DIGIT = re.compile(r"\d")
SPACE = re.compile(r"\s")

UNDEFINED = 0x110000  # sentinel for undefined cp1252 bytes


def ranges(pred) -> list[tuple[int, int]]:
    """Sorted inclusive (start, end) ranges of code points where pred is true."""
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def rust_str(s: str) -> str:
    """Quote a Python str as a Rust string literal."""
    out = ['"']
    for ch in s:
        cp = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= cp <= 0x7E:
            out.append(ch)
        else:
            out.append("\\u{%X}" % cp)
    out.append('"')
    return "".join(out)


def rust_bytes(bs: bytes) -> str:
    """Quote a Python bytes as a Rust byte-string literal."""
    out = ['b"']
    for b in bs:
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 0x20 <= b <= 0x7E:
            out.append(chr(b))
        else:
            out.append(f"\\x{b:02X}")
    out.append('"')
    return "".join(out)


def py_read(data: bytes) -> str:
    """The exact decode chain of strip_srt.py: utf-8-sig, cp1252, utf-8 replace."""
    for enc in ("utf-8-sig", "cp1252"):
        try:
            return data.decode(enc)
        except UnicodeDecodeError:
            pass
    return data.decode("utf-8", "replace")


def emit_ranges(name: str, rs: list[tuple[int, int]], f) -> None:
    f.write("#[rustfmt::skip]\n")
    f.write(f"pub const {name}: &[(u32, u32)] = &[\n")
    for i in range(0, len(rs), 8):
        chunk = rs[i : i + 8]
        f.write("    " + " ".join(f"(0x{s:04X},0x{e:04X})," for s, e in chunk) + "\n")
    f.write("];\n\n")


def main() -> int:
    letter = ranges(lambda cp: bool(LETTER.search(chr(cp))))
    digit = ranges(lambda cp: bool(DIGIT.match(chr(cp))))
    space_re = ranges(lambda cp: bool(SPACE.match(chr(cp))))
    space_str = ranges(lambda cp: chr(cp).isspace())

    # Invariants the Rust side relies on. Adjacent 0-9 blocks merge into one
    # range (math digits: five contiguous sets), so value = (cp - start) % 10.
    assert digit, "no digit ranges"
    for s, e in digit:
        for cp in range(s, e + 1):
            assert int(chr(cp)) == (cp - s) % 10, f"digit value mismatch at 0x{cp:04X}"
    if space_re != space_str:
        only_re = [cp for cp in range(0x110000) if bool(SPACE.match(chr(cp))) != chr(cp).isspace()]
        print(f"FATAL: re \\s != str.isspace() at {len(only_re)} code points, first: {[hex(c) for c in only_re[:10]]}")
        return 1

    cp1252: list[int] = []
    for b in range(256):
        try:
            cp1252.append(ord(bytes([b]).decode("cp1252")))
        except UnicodeDecodeError:
            cp1252.append(UNDEFINED)

    SRC.mkdir(exist_ok=True)
    TESTDATA.mkdir(exist_ok=True)

    ver = f"Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version})"
    with open(SRC / "tables.rs", "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED FILE - do not edit by hand.\n")
        f.write(f"// Generated by tools/gen_tables.py with {ver}.\n")
        f.write("// Oracle: the deprecated Python strip_srt.py behaviors it must match.\n")
        f.write("//  LETTER_RANGES: re [^\\W\\d_]           (has_letter)\n")
        f.write("//  DIGIT_RANGES : re \\d, contiguous 0-9 blocks (timecode fields;\n")
        f.write("//                 digit value = (cp - start) % 10)\n")
        f.write("//  SPACE_RANGES : re \\s == str.isspace() (is_blank, strip, timecode \\s*)\n")
        f.write("//  CP1252_MAP   : cp1252 decode, 0x110000 = undefined byte\n")
        f.write("\n")
        emit_ranges("LETTER_RANGES", letter, f)
        emit_ranges("DIGIT_RANGES", digit, f)
        emit_ranges("SPACE_RANGES", space_re, f)
        f.write("#[rustfmt::skip]\n")
        f.write("pub const CP1252_MAP: [u32; 256] = [\n")
        for i in range(0, 256, 8):
            f.write("    " + " ".join(f"0x{cp:06X}," for cp in cp1252[i : i + 8]) + "\n")
        f.write("];\n")

    # letter_sample.tsv: codepoint, expected has_letter 0/1.
    sample = set(range(0x300))
    for s, e in letter:
        for cp in (s - 1, s, e, e + 1):
            if 0 <= cp <= 0x10FFFF:
                sample.add(cp)
    sample.update(range(0, 0x110000, 61))
    explicit = [0x00B2, 0x2163, 0x0663, 0x4E2D, 0x00E9, 0x00BD, 0x001F, 0x2318, 0xFF3F, 0x0345, 0x2160, 0x0966, 0x1D7CE, 0x10FFFF]
    sample.update(explicit)
    with open(TESTDATA / "letter_sample.tsv", "w", encoding="utf-8", newline="\n") as f:
        for cp in sorted(sample):
            f.write(f"{cp}\t{1 if LETTER.search(chr(cp)) else 0}\n")

    # timecode cases: lines.txt + expected.txt (stamp or NONE).
    lines = [
        "00:00:00,000 --> 00:00:04,040",
        "1:2:3,456 --> x",
        "01:02:03.456\t\t--> 01:02:04.000",
        "01:02:03,456\u00a0--> x",
        "01:02:03,456 -->",
        "x01:02:03,456 --> y",
        "999:59:59,999 --> x",
        "123:45:67,890 --> x",
        "12:34:56,7890 --> x",
        "12:34:56,789 -->x",
        "12:34:56,78 --> x",
        "\u0661\u0662:\u0663\u0664:\u0665\u0666,\u0667\u0668\u0669 --> x",
        "00:00:00,000-->00:00:01,000",
        "0:00:00,000 -->",
        "--> 01:02:03,456",
        "xx:xx:xx,xxx -->",
        "01:02:03,456 \t\u00a0 --> t",
        "\u0661:\u0660\u0662:\u0660\u0663,\u0664\u0665\u0666 --> x",
        "a01:02:03,456 --> b01:02:03,456 -->",
        "00:00:00,000 -> x",
        "\u0967\u0968:\u0969\u096A:\u096B\u096C,\u096D\u096E\u096F --> x",
        "12:34:56,789 \u001F --> x",
        "0:0:00,000 --> x",
        "00:0:00,000 --> x",
    ]
    with open(TESTDATA / "timecode_lines.txt", "w", encoding="utf-8", newline="\n") as fl, open(
        TESTDATA / "timecode_expected.txt", "w", encoding="utf-8", newline="\n"
    ) as fe:
        for line in lines:
            m = re.search(r"(\d{1,2}):(\d{2}):(\d{2})[,.]\d{3}\s*-->", line)
            stamp = f"{int(m.group(1)):02d}:{m.group(2)}:{m.group(3)}" if m else "NONE"
            fl.write(line + "\n")
            fe.write(stamp + "\n")

    # splitlines cases as Rust literals; expected parts computed LIVE by
    # Python's own splitlines() (no hand-written expectations).
    split_inputs = [
        "",
        "\n",
        "\n\n",
        "\r\n",
        "\r",
        "a\r\nb",
        "a\rb",
        "a\r\r\nb",
        "a\n",
        "a\r\n\r",
        "a\nb\rc\vd\fe\x1cg\x1dh\x1ei\x85j\u2028k\u2029l",
        "a\x0bb",
        "x\x85y",
        "a\u2028",
        "hello",
        "\u2028\u2029",
        "a\r\n\r\nb",
        "\r\r",
        "ab\u2028cd",
        "\x1e",
    ]
    split_cases = [(s, s.splitlines()) for s in split_inputs]
    with open(TESTDATA / "splitlines_cases.rs", "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED FILE - do not edit by hand (tools/gen_tables.py).\n")
        f.write("#[rustfmt::skip]\n")
        f.write("pub const CASES: &[(&str, &[&str])] = &[\n")
        for text, parts in split_cases:
            f.write(f"    ({rust_str(text)}, &[{', '.join(rust_str(p) for p in parts)}]),\n")
        f.write("];\n")

    # trim / blank / decode / stem cases as Rust literals.
    trim_cases = [
        ("", ""),
        (" x ", "x"),
        ("\t\u00a0x\u001f ", "x"),
        ("\u3000x\u3000", "x"),
        ("xy", "xy"),
        ("\u0085x", "x"),
        (" x", "x"),
        ("x ", "x"),
        ("\u2000\u2001z\u200a", "z"),
        ("..x..", "..x.."),
        ("\u1680y\u202f", "y"),
    ]
    blank_cases = [
        ("", True), (" ", True), ("\t", True), ("\u00a0", True), ("\u001f", True),
        ("x", False), (" x ", False), ("\u200b", False), ("\u1680", True),
        ("\u3000 ", True), (".", False), ("\u001c", True),
    ]
    decode_inputs = [
        b"",
        b"abc",
        b"\xef\xbb\xbfabc",
        b"\xe9",
        b"caf\xe9",
        b"\x92 \x93quote\x94",
        b"\xff\xfe",
        b"\xef\xbb\xbf\xff",
        b"\x81",
        b"\x81\xe9",
        b"\xed\xa0\x80",
        b"\xf4\x90\x80\x80",
        b"\xc0\x80",
        b"abc\xef\xbb",
        b"\xf0\x9f\x92\xa9",
        b"\x81\xf0\x9f",
        b"\xef\xbb\xbf",
        b"\x90\xf0\x9f\x92\xa9",
        b"\x8d\xed\xa0\x80",
        b"\x8f\xe0\x80\x80",
        b"\x9d\xf4\x90\x80\x80",
        b"\x81\xc0\x80",
        b"\x81\xe2\x82",
        b"\x81\xe2\x28\xa1",
        b"\x81\xf0\x28\x8c\x28",
        b"\x81\xff\xfe",
        b"\x81\xc2",
        b"\x81\xe2\x82\xac",
        b"\x81\x80\x80\x80",
        b"\x81\xf5\x80\x80\x80",
        b"\xef\xbb\xbf\x81",
        b"\x81\xf0\x9f\x92",
        b"\x81\xf0\x9f\x92\xa9",
        b"\x81\xe0\xa0\x80",
        b"\x81\xed\x9f\xbf",
    ]
    stem_names = ["video.srt", "archive.tar.gz", ".hidden", "foo.", "plain", "a.b.c", ".a.b", "a..b", "..", "...", "x.y."]

    def emit_pairs(fname: str, const: str, ty: str, pairs, fmt) -> None:
        with open(TESTDATA / fname, "w", encoding="utf-8", newline="\n") as f:
            f.write("// GENERATED FILE - do not edit by hand (tools/gen_tables.py).\n")
            f.write("#[rustfmt::skip]\n")
            f.write(f"pub const {const}: &[({ty}, {ty})] = &[\n")
            for a, b in pairs:
                f.write(f"    ({fmt(a)}, {fmt(b)}),\n")
            f.write("];\n")

    emit_pairs("trim_cases.rs", "TRIM_CASES", "&str", trim_cases, rust_str)
    with open(TESTDATA / "blank_cases.rs", "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED FILE - do not edit by hand (tools/gen_tables.py).\n")
        f.write("#[rustfmt::skip]\n")
        f.write("pub const BLANK_CASES: &[(&str, bool)] = &[\n")
        for s, v in blank_cases:
            f.write(f"    ({rust_str(s)}, {'true' if v else 'false'}),\n")
        f.write("];\n")
    with open(TESTDATA / "decode_cases.rs", "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED FILE - do not edit by hand (tools/gen_tables.py).\n")
        f.write("#[rustfmt::skip]\n")
        f.write("pub const DECODE_CASES: &[(&[u8], &str)] = &[\n")
        for data in decode_inputs:
            f.write(f"    ({rust_bytes(data)}, {rust_str(py_read(data))}),\n")
        f.write("];\n")
    emit_pairs("stem_cases.rs", "STEM_CASES", "&str", [(n, Path(n).stem) for n in stem_names], rust_str)

    data = (SRC / "tables.rs").read_bytes()
    print(f"oracle: {ver}")
    print(f"LETTER ranges: {len(letter)}  DIGIT ranges: {len(digit)}  SPACE ranges: {len(space_re)}")
    print(f"letter sample rows: {len(sample)}  splitlines cases: {len(split_cases)}")
    print(f"tables.rs: {len(data)} bytes  sha256 {hashlib.sha256(data).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
